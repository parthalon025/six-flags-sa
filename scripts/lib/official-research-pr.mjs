/**
 * Draft PR for scheduled official-site cache refreshes (#410).
 */

export const OFFICIAL_RESEARCH_COMMIT_TITLE = 'Sync official site research caches';

/**
 * @param {string | number} runId
 */
export function officialResearchBranchName(runId) {
  return `sync/official-research-${runId}`;
}

/**
 * @param {{ serverUrl: string, repository: string, runId: string | number, summaryMarkdown: string }} opts
 */
export function composeOfficialResearchPrBody({ serverUrl, repository, runId, summaryMarkdown }) {
  const lines = [
    `Refreshed by [Sync official site research](${serverUrl}/${repository}/actions/runs/${runId}).`,
    '',
    summaryMarkdown,
  ];
  return lines.join('\n');
}

/**
 * Glob-style path for git-add of fleet official-cache sidecars.
 *
 * @param {string} venueDataDir — OVERRIDE_DIR from venue-builder paths
 */
export function officialCacheAddPattern(venueDataDir) {
  return `${venueDataDir}/*/official-cache.json`;
}

/**
 * @param {string} runId
 */
export function officialResearchCommitMessage(runId) {
  return {
    title: OFFICIAL_RESEARCH_COMMIT_TITLE,
    body: `Generated by Sync official site research workflow, run ${runId}.`,
  };
}
