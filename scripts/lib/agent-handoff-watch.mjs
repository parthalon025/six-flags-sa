/**
 * Agent-handoff watch — decision + gh scoping for
 * .github/workflows/agent-handoff-watch.yml.
 *
 * Interface:
 *   shouldTriage(event)
 *   assertScopedGhArgs(args, allowedIssueNumber)
 *   REQUIRED_COMMENT_PREFIX
 */

const AGENT_HANDOFF_LABEL = 'agent-handoff';

/**
 * Every comment this workflow posts must open with this line (the triage
 * skill's AI-disclosure requirement). The workflow's prompt text repeats it
 * verbatim for Claude to read — test/scripts/agent-handoff-watch.test.mjs
 * asserts the two stay in sync so the prompt can't drift from what
 * assertScopedGhArgs actually enforces.
 */
export const REQUIRED_COMMENT_PREFIX = '> *This was generated by AI during triage.*';

/** Does this `issues` webhook event warrant running the triage skill? */
export function shouldTriage(event) {
  if (!event || typeof event !== 'object') return false;
  if (event.action === 'opened') {
    const labels = event.issue?.labels ?? [];
    return labels.some((label) => label?.name === AGENT_HANDOFF_LABEL);
  }
  if (event.action === 'labeled') {
    return event.label?.name === AGENT_HANDOFF_LABEL;
  }
  return false;
}

const ISSUE_SCOPED_SUBCOMMANDS = new Set(['view', 'comment', 'edit']);
const UNSCOPED_READ_SUBCOMMANDS = new Set(['list']);

/** `gh issue edit` may only add/remove triage labels — never retitle, rebody, reassign, etc. */
const EDIT_ALLOWED_FLAGS = new Set(['--add-label', '--remove-label']);

function assertEditFlagsScoped(flags) {
  for (let i = 0; i < flags.length; i += 1) {
    const flag = flags[i];
    if (!flag.startsWith('--')) continue;
    if (!EDIT_ALLOWED_FLAGS.has(flag)) {
      throw new Error(
        `agent-handoff-gh: "gh issue edit ${flag}" is not allowed — only --add-label/--remove-label`,
      );
    }
    i += 1; // skip the flag's value
  }
}

function assertCommentBodyScoped(flags) {
  const bodyIndex = flags.indexOf('--body');
  if (bodyIndex === -1) {
    throw new Error(
      'agent-handoff-gh: "gh issue comment" requires --body with the AI-disclosure prefix',
    );
  }
  const body = flags[bodyIndex + 1] ?? '';
  if (!body.startsWith(REQUIRED_COMMENT_PREFIX)) {
    throw new Error(`agent-handoff-gh: comment body must start with "${REQUIRED_COMMENT_PREFIX}"`);
  }
}

/**
 * Throws unless `args` (a `gh` argv, e.g. `['issue', 'comment', '42', ...]`)
 * is a read, or a comment/label write, scoped to exactly `allowedIssueNumber`.
 * `gh issue list` and `gh search issues` are read-only across the whole repo
 * (needed for the triage skill's duplicate check) and are always allowed.
 * `gh issue edit` may only carry --add-label/--remove-label, and `gh issue
 * comment` must carry the required AI-disclosure prefix. Everything else —
 * close, delete, reopen, retitle, rebody, reassign, `gh pr`, `gh repo`, `gh
 * api`, or any issue/comment/edit naming a different issue — is refused.
 */
export function assertScopedGhArgs(args, allowedIssueNumber) {
  if (!Array.isArray(args) || args.length < 2) {
    throw new Error('agent-handoff-gh: expected a gh subcommand, e.g. "issue view 42"');
  }
  const [group, subcommand, ...rest] = args;

  if (group === 'search' && subcommand === 'issues') return;

  if (group !== 'issue') {
    throw new Error(`agent-handoff-gh: "gh ${group}" is not allowed in this workflow`);
  }
  if (UNSCOPED_READ_SUBCOMMANDS.has(subcommand)) return;
  if (!ISSUE_SCOPED_SUBCOMMANDS.has(subcommand)) {
    throw new Error(`agent-handoff-gh: "gh issue ${subcommand}" is not allowed in this workflow`);
  }

  const [target, ...flags] = rest;
  if (String(target) !== String(allowedIssueNumber)) {
    throw new Error(
      `agent-handoff-gh: refusing "gh issue ${subcommand} ${target}" — this run may only touch issue #${allowedIssueNumber}`,
    );
  }

  if (subcommand === 'edit') assertEditFlagsScoped(flags);
  if (subcommand === 'comment') assertCommentBodyScoped(flags);
}
